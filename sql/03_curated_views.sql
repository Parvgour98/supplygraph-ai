    S.S_SUPPKEY AS SUPPLIER_KEY, S.S_NAME AS SUPPLIER_NAME,
    S.S_ADDRESS AS SUPPLIER_ADDRESS, S.S_PHONE AS SUPPLIER_PHONE,
    S.S_ACCTBAL AS ACCOUNT_BALANCE,
    N.N_NAME AS NATION_NAME, R.R_NAME AS REGION_NAME,
