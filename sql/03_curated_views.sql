-- SupplyGraph AI: Curated Views
-- Zero-copy views over SNOWFLAKE_SAMPLE_DATA.TPCH_SF1 (original TPC-H data).
-- Columns marked [SYNTHETIC] come from the SYN_ enrichment tables in 02_synthetic_reference_data.sql.
-- Plant assignment rule [SYNTHETIC]: PLANT_KEY = MOD(PART_KEY, 10) + 1.

-- Regions: Nation-region mapping
CREATE OR REPLACE VIEW SUPPLYGRAPH_AI.SUPPLY_CHAIN.V_REGIONS AS
SELECT
    R.R_REGIONKEY AS REGION_KEY, R.R_NAME AS REGION_NAME,
    N.N_NATIONKEY AS NATION_KEY, N.N_NAME AS NATION_NAME
FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.REGION R
JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.NATION N ON R.R_REGIONKEY = N.N_REGIONKEY;

