-- Supplier-Part: Catalog with availability, cost, margin
CREATE OR REPLACE VIEW SUPPLYGRAPH_AI.SUPPLY_CHAIN.V_SUPPLIER_PARTS AS
SELECT
    PS.PS_PARTKEY AS PART_KEY, PS.PS_SUPPKEY AS SUPPLIER_KEY,
    PS.PS_AVAILQTY AS AVAILABLE_QUANTITY, PS.PS_SUPPLYCOST AS SUPPLY_COST,
    P.P_NAME AS PART_NAME, P.P_BRAND AS BRAND, P.P_TYPE AS PART_TYPE,
    P.P_RETAILPRICE AS RETAIL_PRICE,
    S.S_NAME AS SUPPLIER_NAME, N.N_NAME AS SUPPLIER_NATION, R.R_NAME AS SUPPLIER_REGION,
    PS.PS_AVAILQTY * PS.PS_SUPPLYCOST AS INVENTORY_VALUE,
    CASE WHEN PS.PS_SUPPLYCOST > 0
         THEN ROUND((P.P_RETAILPRICE - PS.PS_SUPPLYCOST) / PS.PS_SUPPLYCOST * 100, 2)
         ELSE NULL END AS MARGIN_PERCENTAGE,
    PL.PLANT_KEY, PL.PLANT_NAME, PL.PLANT_REGION                       -- [SYNTHETIC]
FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.PARTSUPP PS
JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.PART P ON PS.PS_PARTKEY = P.P_PARTKEY
JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.SUPPLIER S ON PS.PS_SUPPKEY = S.S_SUPPKEY
JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.NATION N ON S.S_NATIONKEY = N.N_NATIONKEY
JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.REGION R ON N.N_REGIONKEY = R.R_REGIONKEY
LEFT JOIN SUPPLYGRAPH_AI.SUPPLY_CHAIN.SYN_PLANTS PL ON PL.PLANT_KEY = MOD(PS.PS_PARTKEY, 10) + 1;

